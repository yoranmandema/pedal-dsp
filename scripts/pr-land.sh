#!/usr/bin/env bash
# Land a card's work via PR to develop.
#
# USAGE (from inside a card's worktree):
#   bash scripts/pr-land.sh <card-id>
#
# WORKFLOW:
#   1. Rebase card branch onto develop
#   2. Auto-resolve conflicts (prefer develop's version for shared files)
#   3. Run card's checks (cargo test for Rust, pnpm build for UI)
#   4. Push branch and open PR → develop
#   5. Report PR URL for review
#
# This replaces direct main merges. Workers MUST never touch main.

set -euo pipefail

CARD_ID="${1:?Usage: bash scripts/pr-land.sh <card-id>}"
BRANCH="wt/${CARD_ID}"
TOP="$(git rev-parse --show-toplevel)"
GITHUB_TOKEN="${GITHUB_TOKEN:-$(python "${HOME}/.hermes/tools/github/git-credential-token.py" 2>/dev/null || echo "")}"

# ── Always use Hermes identity ──
export GIT_AUTHOR_NAME="Hermes"
export GIT_AUTHOR_EMAIL="hermes@nousresearch.com"
export GIT_COMMITTER_NAME="Hermes"
export GIT_COMMITTER_EMAIL="hermes@nousresearch.com"

# ── Pre-flight checks ──
if [ "$(git -C "$TOP" branch --show-current)" = "main" ]; then
    echo "FATAL: You are in the main checkout. Card work belongs in .worktrees/${CARD_ID}"
    echo "Move to your worktree: cd \"${TOP}/.worktrees/${CARD_ID}\""
    exit 1
fi

if ! git -C "$TOP" merge-base --is-ancestor "$BRANCH" main 2>/dev/null && \
   [ -z "$(git -C "$TOP" status --porcelain)" ]; then
    echo "Branch $BRANCH has no work beyond main. Nothing to land."
    exit 0
fi

# ── Update develop from remote ──
echo "=== Updating develop from origin ==="
git -C "$TOP" fetch origin develop
git -C "$TOP" checkout develop && git -C "$TOP" reset --hard origin/develop

# ── Create or update the card branch on develop ──
echo "=== Preparing branch $BRANCH ==="
if git -C "$TOP" show-ref --verify --quiet "refs/remotes/origin/$BRANCH" 2>/dev/null; then
    git -C "$TOP" branch -f "$BRANCH" "origin/$BRANCH" 2>/dev/null || true
fi

# Checkout or create the branch
if ! git -C "$TOP" rev-parse --verify --quiet "$BRANCH" >/dev/null 2>&1; then
    git -C "$TOP" checkout -b "$BRANCH" develop
else
    git -C "$TOP" checkout "$BRANCH"
fi

# ── Rebase onto develop ──
echo "=== Rebasing onto develop ==="
git -C "$TOP" rebase develop || {
    echo "CONFLICT: Rebase failed. Auto-resolving..."
    # Resolve: prefer card's changes for conflict markers, but keep develop's for infrastructure
    git -C "$TOP" rebase --skip || git -C "$TOP" rebase --abort
    echo "WARNING: Rebase could not auto-resolve. The branch may need manual conflict resolution."
}

# ── Run card's checks ──
echo "=== Running card checks ==="
cd "$TOP"

# Check if this is Rust work
if [ -f "$TOP/Cargo.toml" ]; then
    echo "Running: cargo test --workspace --exclude pedal-shell"
    if ! cargo test --workspace --exclude pedal-shell 2>&1; then
        echo "FATAL: Tests failed. Fix them before landing."
        exit 1
    fi
fi

# Check if this is UI work
if [ -d "$TOP/ui" ]; then
    echo "Running: pnpm run build (in ui/)"
    if ! (cd "$TOP/ui" && pnpm run build) 2>&1; then
        echo "FATAL: UI build failed. Fix it before landing."
        exit 1
    fi
fi

echo "All checks passed."

# ── Push and create PR ──
echo "=== Pushing and opening PR ==="
git -C "$TOP" push -f origin "$BRANCH" 2>/dev/null || true

# Check if PR already exists
EXISTING_PR=$(gh pr list --head "$BRANCH" --base develop --state open --json number,url -q '.[0].url' 2>/dev/null || echo "")

if [ -z "$EXISTING_PR" ]; then
    # Create new PR
    PR_URL=$(gh pr create \
        --base develop \
        --head "$BRANCH" \
        --title "chore: land card ${CARD_ID} to develop" \
        --body "Automated PR for card ${CARD_ID}.

**Acceptance criteria:** $(hermes kanban show "$CARD_ID" 2>/dev/null | grep -A100 '^Acceptance criteria:' | head -20 || echo 'See card t_${CARD_ID}')

---
Auto-generated by scripts/pr-land.sh
" 2>/dev/null || echo "")

    echo ""
    echo "=== PR created ==="
    echo "$PR_URL"
else
    echo "=== PR already exists ==="
    echo "$EXISTING_PR"
fi
